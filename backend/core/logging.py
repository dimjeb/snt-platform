"""
Фильтр журналирования: персональные данные не должны попадать в логи.

152-ФЗ не запрещает вести журналы, но логи — самое частое место утечки:
их читает любой, у кого есть доступ к серверу, они уезжают в системы
мониторинга и живут дольше самих данных. Дешевле не писать ПДн вовсе,
чем потом доказывать, что доступ к ним был разграничен.

Фильтр намеренно перестраховывается: лучше замазать лишний десятизначный
номер, чем пропустить телефон. В диагностике это почти не мешает —
идентификаторы записей и трассировки остаются нетронутыми.
"""
import logging
import re

# Телефон: 10–11 цифр с обычными разделителями. Точка разделителем не
# считается — иначе под маску попали бы IP-адреса вида 192.168.103.160.
_PHONE = re.compile(
    r"(?<![\d.])(?:\+?7|8)?[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]?\d{2}[\s\-]?\d{2}(?![\d.])"
)
_EMAIL = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")
# Значения параметров, через которые ФИО попадает в строку запроса.
# Маскируем только их: ?page=2 в логе полезен и ничего не раскрывает.
_QUERY_VALUE = re.compile(
    r"(?i)\b(search|q|query|phone|email|fio|name|last_name|first_name)=([^&\s\"'>]*)"
)

PHONE_MASK = "<телефон скрыт>"
EMAIL_MASK = "<email скрыт>"
VALUE_MASK = "<скрыто>"


def scrub(text):
    """Убрать из строки телефоны, адреса почты и поисковые запросы по ФИО."""
    if not isinstance(text, str):
        return text
    text = _EMAIL.sub(EMAIL_MASK, text)
    text = _PHONE.sub(PHONE_MASK, text)
    text = _QUERY_VALUE.sub(lambda m: f"{m.group(1)}={VALUE_MASK}", text)
    return text


class PIIFilter(logging.Filter):
    """
    Чистит запись журнала перед тем, как её увидит хоть один обработчик.

    Сообщение форматируется здесь же, а args обнуляются: иначе обработчик
    подставит в уже очищенный шаблон неочищенные аргументы, и вся работа
    пропадёт. Ленивое форматирование мы теряем сознательно — логов тут
    немного, а утечка стоит дороже.
    """

    def filter(self, record):
        try:
            message = record.getMessage()
        except Exception:
            # Шаблон и аргументы не сошлись — Django такое тоже переживёт
            # при выводе, но чистить всё равно надо, иначе ПДн уедут
            # в лог через args.
            record.msg = scrub(str(record.msg))
            record.args = tuple(
                scrub(a) if isinstance(a, str) else a for a in (record.args or ())
            )
            return True
        record.msg = scrub(message)
        record.args = ()
        return True
